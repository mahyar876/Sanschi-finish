const { normalizeText } = require('./assistantParse');

/**
 * تشخیص سؤالات متداول / پشتیبانی — بدون ادعای انجام عملیات واقعی.
 * @returns {{ type: string, confidence: 'high' | 'medium' } | null}
 */
function detectAssistantTopic(message) {
  const t = normalizeText(message);
  if (!t || t.length < 3) return null;

  const rules = [
    {
      type: 'what_is_sanschii',
      re: /سانس\s*چی\s*چیه|سانس\s*چیی\s*چیه|سانسچی\s*چیه|sanschii?\s*چیه|سانس\s*چی\s*چی\s*است/,
    },
    {
      type: 'how_to_book',
      re: /چطور\s*(?:زمین|سانس)\s*رزرو|چگونه\s*رزرو|نحوه\s*رزرو|چطور\s*رزرو\s*کنم/,
    },
    {
      type: 'how_see_price',
      re: /قیمت\s*(?:زمین|چمن|فوتسال)?\s*چنده|قیمت\s*چقد|چقد\s*قیمت|هزینه\s*چقد/,
    },
    {
      type: 'is_online',
      re: /رزرو\s*آنلاین|آنلاین\s*رزرو|اینترنتی\s*رزرو/,
    },
    {
      type: 'how_check_availability',
      re: /سانس\s*آزاد|خالی\s*بود|چطور\s*بفهمم\s*.*(?:آزاد|خالی)|موجود\s*بود/,
    },
    {
      type: 'after_payment',
      re: /بعد\s*از\s*پرداخت|پرداخت\s*کردم\s*چی|پرداخت\s*موفق/,
    },
    {
      type: 'payment_failed',
      re: /پرداخت\s*ناموفق|پرداخت\s*نشد|خطا\s*در\s*پرداخت/,
    },
    {
      type: 'payment_deducted_no_booking',
      re: /پول\s*.*کم\s*شد|کسر\s*شد.*رزرو\s*نشد|پرداخت\s*شد\s*ولی\s*رزرو/,
    },
    {
      type: 'payment_confirm_question',
      re: /پرداخت\s*کنم\s*رزرو\s*قطعی|رزرو\s*قطعی\s*می\s*ش|تأیید\s*می\s*ش|تایید\s*می\s*ش/,
    },
    {
      type: 'view_reservations',
      re: /رزرو\s*(?:های\s*)?من|رزرو\s*خودم|رزروهای\s*قبلی|ببینم\s*رزرو/,
    },
    {
      type: 'cancel_reservation',
      re: /لغو\s*رزرو|کنسل\s*رزرو|رزرو\s*قبلی.*لغو/,
    },
    {
      type: 'refund_policy',
      re: /بازگشت\s*وجه|استرداد|پول\s*برگشت|عودت\s*وجه/,
    },
    {
      type: 'pitch_unavailable',
      re: /زمین\s*.*(?:نبود|در\s*دسترس\s*نبود)|سانس\s*.*(?:نبود|پر\s*بود)/,
    },
    {
      type: 'contact_support',
      re: /پشتیبانی|تماس\s*با\s*سانس|کمک\s*بگیر|support/,
    },
    {
      type: 'slot_now_free',
      re: /(?:این\s*زمین|همین\s*زمین|الان)\s*.*(?:خالی|آزاد)|خالی\s*است\s*\?/,
    },
  ];

  for (const row of rules) {
    if (row.re.test(t)) {
      return { type: row.type, confidence: 'high' };
    }
  }

  const hasBookingWords =
    /زمین|چمن|فوتسال|پیدا\s*کن/.test(t) ||
    (/میخوام|رزرو\s*کن/.test(t) && !/لغو|کنسل|رزرو\s*های\s*من|رزرو\s*خودم/.test(t));

  if (hasBookingWords && !/سانس\s*چی|sanschii\s*چی|سانسچی\s*چی/.test(t)) {
    return null;
  }

  return null;
}

