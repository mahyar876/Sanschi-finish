function row(key, zone, ...extra) {
  const match = new Set();
  const push = (s) => {
    const t = String(s || '').trim();
    if (!t) return;
    match.add(t);
    match.add(t.replace(/\u200c/g, ''));
    match.add(t.replace(/\u200c/g, '').replace(/\s+/g, ''));
    if (t.includes(' ')) match.add(t.replace(/\s+/g, ' '));
  };
  push(key);
  for (const e of extra) push(e);

  const matchList = [...match].filter((s) => s.length >= 2);
  const addressMatch = matchList.filter((s) => s.replace(/\s/g, '').length >= 3);

  return {
    key,
    zone,
    match: matchList,
    addressMatch: addressMatch.length ? addressMatch : matchList,
  };
}

/** حذف تکراری نام یکسان */
function dedupeByKey(list) {
  const seen = new Set();
  const out = [];
  for (const item of list) {
    if (seen.has(item.key)) continue;
    seen.add(item.key);
    out.push(item);
  }
  return out;
}

const TEHRAN_DISTRICTS = dedupeByKey(ENTRIES.map((e) => row(e[0], e[1], ...e.slice(2))));

