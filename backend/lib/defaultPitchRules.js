/** قوانین پیش‌فرض مجموعه — هر خط یک بند (هم‌خوان با web/src/lib/pitch-default-rules.ts) */

const COMMON = [
  'رزرو پس از پرداخت آنلاین قطعی است و سانس برای سایرین بسته می‌شود.',
  'حضور حداقل ۱۰ دقیقه قبل از شروع سانس الزامی است.',
  'در صورت تأخیر بیش از ۱۵ دقیقه، مدت باقی‌مانده سانس بدون بازگشت مبلغ محاسبه می‌شود.',
  'لغو رزرو تا ۲۴ ساعت قبل از سانس (طبق سیاست سانس‌چی) امکان‌پذیر است؛ پس از آن مشمول جریمه یا عدم استرداد می‌شود.',
  'استفاده از توپ و تجهیزات شخصی فقط در صورت عدم آسیب به کف و تجهیزات مجموعه مجاز است.',
  'مسئولیت هرگونه خسارت ناشی از رفتار بازیکنان بر عهده رزروکننده است.',
  'رعایت نظافت، سکوت نسبی و احترام به سانس بعدی الزامی است.',
];

const FUTSAL = [
  'ورود با کفش آجدار، چرم یا کفش خیابانی به سالن ممنوع است.',
  'استعمال دخانیات، قلیان و مواد خوراکی پرحجم داخل سالن ممنوع است.',
  'تغییر سانس یا زمین بدون هماهنگی با پذیرش ممکن نیست.',
];

const GRASS = [
  'استفاده از کفش دارای فشار (stud) فقط در صورت مجاز بودن توسط مجموعه و بدون آسیب به چمن است.',
  'در صورت بارش شدید یا تعطیلی فضای باز، سانس ممکن است جابه‌جا یا لغو شود؛ هماهنگی از طریق پشتیبانی انجام می‌شود.',
  'ورود افراد غیربازیکن به زمین بدون هماهنگی ممنوع است.',
];

const LARGE_PITCH = [
  'حداکثر تعداد بازیکن در هر سانس نباید از ظرفیت ثبت‌شده در صفحه مجموعه بیشتر شود.',
];

/**
 * @param {'futsal' | 'grass'} type
 * @param {5 | 7 | 11} size
 */
function buildDefaultPitchRules(type, size) {
  const lines = [...COMMON];
  if (type === 'grass') lines.push(...GRASS);
  else lines.push(...FUTSAL);
  if (size === 7 || size === 11) lines.push(...LARGE_PITCH);
  return lines.join('\n');
}

module.exports = { buildDefaultPitchRules };
